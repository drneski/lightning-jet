// Package report summarizes each channel's economics from the latest cycle's
// records: what it earned over the observation window and what that yields on
// its capacity, the forwards that failed for lack of balance, what the
// estimator expects next, what competing channels charge, and what Jet
// decided. It reads Jet's records only, never LND.
//
// A peer's channels are one row, as Jet decides about them: their totals,
// under the first of them, with each channel listed under it.
package report

import (
	"sort"
	"time"

	"github.com/drneski/lightning-jet/v2/internal/contracts"
	"github.com/drneski/lightning-jet/v2/internal/economics"
	"github.com/drneski/lightning-jet/v2/internal/peer"
	"github.com/drneski/lightning-jet/v2/internal/store"
)

// Report is the economics of every channel as of one cycle.
type Report struct {
	SnapshotID  string    `json:"snapshot_id"`
	TakenAt     time.Time `json:"taken_at"`
	WindowHours int64     `json:"window_hours"`
	Totals      Totals    `json:"totals"`
	// Channels are one per peer: a peer's channels together, under the first.
	Channels []Channel `json:"channels"`
	// Routes are the forwards by the pair of peers they came in and left
	// through, each peer named by its first channel, the ones that earned the
	// most first.
	Routes []Route `json:"routes,omitempty"`
	// Refills are the cycle's refill evaluations, in channel order.
	Refills []Refilled `json:"refills,omitempty"`
}

// Refilled is one refill evaluation: a proposal and its verdict, or an
// abstention. Detail is the proposal's rationale or the abstention's detail,
// generated by Jet, and WouldChangeIf what would make it refill.
type Refilled struct {
	ChanID        contracts.ChanID           `json:"chan_id"`
	SCID          string                     `json:"scid"`
	Source        *contracts.ChanID          `json:"source_chan_id,omitempty"`
	AmountMsat    contracts.MilliSat         `json:"amount_msat,omitempty"`
	MaxFeeMsat    contracts.MilliSat         `json:"max_fee_msat,omitempty"`
	Verdict       contracts.Verdict          `json:"verdict,omitempty"`
	Mode          contracts.Mode             `json:"mode,omitempty"`
	Blocked       []string                   `json:"blocked,omitempty"`
	Abstained     contracts.AbstentionReason `json:"abstained,omitempty"`
	Detail        string                     `json:"detail"`
	WouldChangeIf []string                   `json:"would_change_if,omitempty"`
}

// Route is the forwards that came in through one channel and left through
// another.
type Route struct {
	In            contracts.ChanID   `json:"chan_id_in"`
	InSCID        string             `json:"scid_in"`
	Out           contracts.ChanID   `json:"chan_id_out"`
	OutSCID       string             `json:"scid_out"`
	Count         int                `json:"count"`
	AmountOutMsat contracts.MilliSat `json:"amount_out_msat"`
	FeeMsat       contracts.MilliSat `json:"fee_msat"`
}

// Channel is one channel's economics, or a peer's channels' together: then
// ChanIDs lists them, ChanID first, every value is theirs together, and
// Channels has each one's own.
type Channel struct {
	ChanID contracts.ChanID `json:"chan_id"`
	// SCID is the channel id as block x transaction x output.
	SCID     string             `json:"scid"`
	ChanIDs  []contracts.ChanID `json:"chan_ids,omitempty"`
	Channels []Member           `json:"members,omitempty"`
	Peer     string             `json:"peer"`
	// PeerAlias is the alias the peer announced, as recorded: untrusted text.
	PeerAlias    string             `json:"peer_alias,omitempty"`
	Active       bool               `json:"active"`
	CapacityMsat contracts.MilliSat `json:"capacity_msat"`
	LocalMsat    contracts.MilliSat `json:"local_msat"`
	RemoteMsat   contracts.MilliSat `json:"remote_msat"`
	// FeePPM is our outbound fee rate: what we charge to forward out through
	// the channel.
	FeePPM   *int64             `json:"out_fee_ppm,omitempty"`
	Forwards contracts.Forwards `json:"forwards"`
	// YieldPct is the fees earned over the window, as a yearly percentage of
	// the channel's capacity.
	YieldPct    float64                `json:"yield_pct_per_year"`
	Failures    *contracts.Failures    `json:"failures,omitempty"`
	Competition *contracts.Competition `json:"competition,omitempty"`
	Forecast    *Forecast              `json:"forecast,omitempty"`
	Refill      *Refill                `json:"refill,omitempty"`
	// Result is the cycle's decision in jet status's words. Abstained, or
	// Proposal with its Verdict and the rules it failed, say the same in parts.
	Result    string                     `json:"result"`
	Abstained contracts.AbstentionReason `json:"abstained,omitempty"`
	Proposal  *contracts.FeeParameters   `json:"proposal,omitempty"`
	Verdict   contracts.Verdict          `json:"verdict,omitempty"`
	Blocked   []string                   `json:"blocked,omitempty"`
	// Mode is the mode a proposal was decided in, and PriorApprovals the fee
	// changes to the channel approved in that mode in the 24 hours before.
	Mode           contracts.Mode `json:"mode,omitempty"`
	PriorApprovals int            `json:"prior_approvals_24h,omitempty"`
}

// Member is one of a peer's channels, when it has several.
type Member struct {
	ChanID       contracts.ChanID   `json:"chan_id"`
	SCID         string             `json:"scid"`
	Active       bool               `json:"active"`
	CapacityMsat contracts.MilliSat `json:"capacity_msat"`
	LocalMsat    contracts.MilliSat `json:"local_msat"`
	RemoteMsat   contracts.MilliSat `json:"remote_msat"`
	FeePPM       *int64             `json:"out_fee_ppm,omitempty"`
	Forwards     contracts.Forwards `json:"forwards"`
}

// Forecast is the estimator's outbound revenue forecast for a channel.
type Forecast struct {
	HorizonHours int64                     `json:"horizon_hours"`
	ExpectedMsat contracts.MilliSat        `json:"expected_msat"`
	LowMsat      contracts.MilliSat        `json:"low_msat"`
	HighMsat     contracts.MilliSat        `json:"high_msat"`
	Interval     string                    `json:"interval"`
	Confidence   contracts.ConfidenceLevel `json:"confidence"`
}

// Refill is the estimator's replacement cost for a channel: what putting
// liquidity back on our side costs, in ppm of the amount moved.
type Refill struct {
	ExpectedPPM int64                     `json:"expected_ppm"`
	LowPPM      int64                     `json:"low_ppm"`
	HighPPM     int64                     `json:"high_ppm"`
	Interval    string                    `json:"interval"`
	Confidence  contracts.ConfidenceLevel `json:"confidence"`
}

// Totals add up the channels. Forecasts are summed only over the channels
// that have one.
type Totals struct {
	Channels            int                `json:"channels"`
	Active              int                `json:"active"`
	CapacityMsat        contracts.MilliSat `json:"capacity_msat"`
	LocalMsat           contracts.MilliSat `json:"local_msat"`
	OutCount            int                `json:"out_count"`
	OutAmountMsat       contracts.MilliSat `json:"out_amount_msat"`
	OutFeeMsat          contracts.MilliSat `json:"out_fee_msat"`
	YieldPct            float64            `json:"yield_pct_per_year"`
	BalanceFailures     int                `json:"balance_failures"`
	BalanceFailuresMsat contracts.MilliSat `json:"balance_failures_msat"`
	CoverageHours       int64              `json:"coverage_hours"`
	Forecasts           int                `json:"forecasts"`
	HorizonHours        int64              `json:"horizon_hours"`
	ExpectedMsat        contracts.MilliSat `json:"expected_msat"`
}

// Build assembles a report from one cycle: its snapshot, the estimates made
// from it, and the cycle's per-channel results.
func Build(snap *contracts.Snapshot, estimates []*contracts.Estimate, status *store.Status) *Report {
	results := map[contracts.ChanID]store.ChannelStatus{}
	for _, c := range status.PerChannel {
		results[c.ChanID] = c
	}
	forecasts := map[contracts.ChanID]*Forecast{}
	refills := map[contracts.ChanID]*Refill{}
	var horizon int64
	for _, e := range estimates {
		if e.Kind == economics.KindReplacementCost && e.ExpectedPPM != nil && e.LowPPM != nil && e.HighPPM != nil {
			refills[e.ChanID] = &Refill{ExpectedPPM: *e.ExpectedPPM, LowPPM: *e.LowPPM, HighPPM: *e.HighPPM,
				Interval: e.Interval, Confidence: e.EconomicConfidence.Level}
		}
		if e.Kind != economics.KindOutboundRevenue {
			continue
		}
		horizon = e.HorizonHours
		if e.ExpectedMsat == nil {
			continue
		}
		forecasts[e.ChanID] = &Forecast{HorizonHours: e.HorizonHours, ExpectedMsat: *e.ExpectedMsat, LowMsat: deref(e.LowMsat),
			HighMsat: deref(e.HighMsat), Interval: e.Interval, Confidence: e.EconomicConfidence.Level}
	}

	r := &Report{SnapshotID: snap.ID, TakenAt: snap.TakenAt}
	t := &r.Totals
	t.HorizonHours = horizon
	lead := map[contracts.ChanID]contracts.ChanID{}
	for _, g := range peer.Groups(snap.Channels) {
		c := g.Combined
		res := results[c.ChanID]
		ch := Channel{ChanID: c.ChanID, SCID: c.ChanID.SCID(), ChanIDs: g.IDs(), Peer: c.Peer, PeerAlias: c.PeerAlias, Active: c.Active,
			CapacityMsat: c.CapacityMsat, LocalMsat: c.LocalMsat, RemoteMsat: c.RemoteMsat, Forwards: c.Forwards,
			YieldPct: yield(c.Forwards.OutFeeMsat, c.CapacityMsat, c.Forwards.WindowHours),
			Failures: c.Failures, Competition: c.Competition, Forecast: forecasts[c.ChanID], Refill: refills[c.ChanID],
			Result: res.Result(), Abstained: res.Abstained, Proposal: res.Proposal, Verdict: res.Verdict, Blocked: res.Blocked,
			Mode: res.Mode, PriorApprovals: res.PriorApprovals}
		ch.FeePPM = feePPM(c.OurPolicy)
		for _, m := range g.Channels {
			lead[m.ChanID] = c.ChanID
			t.Channels++
			if m.Active {
				t.Active++
			}
			if len(g.Channels) > 1 {
				ch.Channels = append(ch.Channels, Member{ChanID: m.ChanID, SCID: m.ChanID.SCID(), Active: m.Active,
					CapacityMsat: m.CapacityMsat, LocalMsat: m.LocalMsat, RemoteMsat: m.RemoteMsat, FeePPM: feePPM(m.OurPolicy),
					Forwards: m.Forwards})
			}
		}
		r.Channels = append(r.Channels, ch)
		r.WindowHours = max(r.WindowHours, c.Forwards.WindowHours)

		t.CapacityMsat += c.CapacityMsat
		t.LocalMsat += c.LocalMsat
		t.OutCount += c.Forwards.OutCount
		t.OutAmountMsat += c.Forwards.OutAmountMsat
		t.OutFeeMsat += c.Forwards.OutFeeMsat
		if f := c.Failures; f != nil {
			t.BalanceFailures += f.BalanceFailures
			t.BalanceFailuresMsat += f.BalanceFailuresMsat
			t.CoverageHours = max(t.CoverageHours, f.CoverageHours)
		}
		if f := ch.Forecast; f != nil {
			t.Forecasts++
			t.ExpectedMsat += f.ExpectedMsat
		}
	}
	t.YieldPct = yield(t.OutFeeMsat, t.CapacityMsat, r.WindowHours)

	// Routes go by peer, named by its first channel. A channel that has since
	// closed stays as it is.
	byPair := map[[2]contracts.ChanID]*Route{}
	for _, rt := range snap.Routes {
		in, out := rt.In, rt.Out
		if l, ok := lead[in]; ok {
			in = l
		}
		if l, ok := lead[out]; ok {
			out = l
		}
		p := byPair[[2]contracts.ChanID{in, out}]
		if p == nil {
			r.Routes = append(r.Routes, Route{In: in, InSCID: in.SCID(), Out: out, OutSCID: out.SCID()})
			p = &r.Routes[len(r.Routes)-1]
			byPair[[2]contracts.ChanID{in, out}] = p
		}
		p.Count += rt.Count
		p.AmountOutMsat += rt.AmountOutMsat
		p.FeeMsat += rt.FeeMsat
	}
	for _, rs := range status.Refills {
		rf := Refilled{ChanID: rs.ChanID, SCID: rs.ChanID.SCID()}
		switch {
		case rs.Intent != nil:
			in := rs.Intent
			rf.Source, rf.Detail = in.Target.SourceChanID, in.Rationale.Summary
			if in.Parameters.Rebalance != nil {
				rf.AmountMsat = in.Parameters.Rebalance.AmountMsat
			}
			if in.Limits.MaxFeeMsat != nil {
				rf.MaxFeeMsat = *in.Limits.MaxFeeMsat
			}
			if d := rs.Decision; d != nil {
				rf.Verdict, rf.Mode = d.Verdict, d.Mode
				for _, rule := range d.Rules {
					if !rule.Passed {
						rf.Blocked = append(rf.Blocked, rule.Rule)
					}
				}
			}
		case rs.Abstention != nil:
			rf.Abstained, rf.Detail, rf.WouldChangeIf = rs.Abstention.Reason, rs.Abstention.Detail, rs.Abstention.WouldChangeIf
		}
		r.Refills = append(r.Refills, rf)
	}
	sort.SliceStable(r.Routes, func(i, j int) bool {
		a, b := r.Routes[i], r.Routes[j]
		if a.FeeMsat != b.FeeMsat {
			return a.FeeMsat > b.FeeMsat
		}
		return a.Count > b.Count
	})
	return r
}

// yield is fees earned over a window, as a yearly percentage of capacity.
func yield(fees, capacity contracts.MilliSat, windowHours int64) float64 {
	if capacity <= 0 || windowHours <= 0 {
		return 0
	}
	return float64(fees) / float64(capacity) * (365 * 24 / float64(windowHours)) * 100
}

func feePPM(p *contracts.Policy) *int64 {
	if p == nil {
		return nil
	}
	ppm := p.FeePPM
	return &ppm
}

func deref(m *contracts.MilliSat) contracts.MilliSat {
	if m == nil {
		return 0
	}
	return *m
}
